// Generates the service-worker source. The worker precaches the entire site on
// install so that after a single online visit the whole vault (every note page,
// graph data, search index, and static assets) is readable offline. Cache is
// versioned per build; a new deploy drops the old cache and repopulates.
//
// `urls` are scope-relative (e.g. "index.html", "graph.json", "notes/x.html").
// The worker lives at the site root, so these resolve against its own location.

export function serviceWorkerSource({ version, urls }) {
  return `// AUTO-GENERATED by build.mjs — do not edit by hand.
const VERSION = ${JSON.stringify(String(version))};
const CACHE = 'mindmap-' + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', function (event) {
  event.waitUntil((async function () {
    const cache = await caches.open(CACHE);
    // Cache in batches so one failed request can't abort the whole precache.
    const batchSize = 40;
    for (let i = 0; i < PRECACHE.length; i += batchSize) {
      const batch = PRECACHE.slice(i, i + batchSize);
      await Promise.allSettled(batch.map(function (u) {
        return cache.add(new Request(u, { cache: 'reload' }));
      }));
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', function (event) {
  event.waitUntil((async function () {
    const keys = await caches.keys();
    await Promise.all(keys.map(function (k) {
      if (k !== CACHE && k.indexOf('mindmap-') === 0) return caches.delete(k);
    }));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', function (event) {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Only handle same-origin requests; cross-origin (e.g. Wikipedia math SVGs,
  // external links) fall through to the network untouched.
  if (url.origin !== self.location.origin) return;
  event.respondWith((async function () {
    const cache = await caches.open(CACHE);
    // ignoreSearch so graph.html?focus=... matches the cached graph.html.
    const cached = await cache.match(req, { ignoreSearch: true });
    if (cached) return cached;
    try {
      const res = await fetch(req);
      if (res && res.ok && res.type === 'basic') cache.put(req, res.clone());
      return res;
    } catch (err) {
      // Offline and never cached: fall back to the app shell for navigations.
      if (req.mode === 'navigate') {
        const shell = await cache.match(new URL('index.html', self.registration.scope).href);
        if (shell) return shell;
      }
      throw err;
    }
  })());
});
`;
}
